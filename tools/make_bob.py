#!/usr/bin/env python3
"""Bob, Datarails' panda mascot, as an 8-bit sprite for the Solitaire win (src/apps/solitaire.js).

  python3 tools/make_bob.py <Bob's picture (plain white background)>

Clears the background (and the gap between his legs and the floor shadow), boosts the colours, shrinks him to a real
46-pixel-wide grid with 18 colours, adds a dark 1-pixel outline and blows it up 4x with hard pixels. Writes
src/bob.js (FR.data.images.bob), which build.py loads after src/assets.js. Needs Pillow.
"""
import base64, io, os, sys
from PIL import Image, ImageEnhance, ImageFilter
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_portraits import clear_background

GRID_W, COLORS, SCALE, OUTLINE = 46, 18, 4, (24, 20, 28, 255)
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def sprite(path):
    im = clear_background(Image.open(path)); px = im.load(); w, h = im.size
    for y in range(int(h * 0.62), h):          # below the waist only: his fur is white too
        for x in range(w):
            r, g, b, a = px[x, y]
            grey = max(r, g, b) - min(r, g, b)
            if a and ((min(r, g, b) > 236 and grey < 10) or (y > h * 0.9 and min(r, g, b) > 170 and grey < 14)): px[x, y] = (0, 0, 0, 0)
    im = im.crop(im.getbbox())
    rgb = ImageEnhance.Contrast(ImageEnhance.Color(im.convert('RGB')).enhance(1.55)).enhance(1.15)
    im = Image.merge('RGBA', (*rgb.split(), im.getchannel('A')))
    gh = round(im.height * GRID_W / im.width)
    small = im.resize((GRID_W, gh), Image.BOX)
    a = small.getchannel('A').point(lambda v: 255 if v >= 140 else 0)
    base = Image.new('RGB', small.size, (255, 255, 255)); base.paste(small, mask=a)
    pal = base.quantize(colors=COLORS, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE).convert('RGBA'); pal.putalpha(a)
    W, H = GRID_W + 2, gh + 2
    out = Image.new('RGBA', (W, H), (0, 0, 0, 0)); out.paste(pal, (1, 1), pal)
    alpha = out.getchannel('A'); grown = alpha.filter(ImageFilter.MaxFilter(3)).load(); al = alpha.load(); op = out.load()
    for y in range(H):
        for x in range(W):
            if grown[x, y] and not al[x, y]: op[x, y] = OUTLINE
    buf = io.BytesIO(); out.resize((W * SCALE, H * SCALE), Image.NEAREST).save(buf, 'PNG', optimize=True)
    return buf.getvalue(), (W, H)


if __name__ == '__main__':
    if len(sys.argv) < 2: raise SystemExit(__doc__)
    png, (w, h) = sprite(sys.argv[1])
    open(os.path.join(root, 'src', 'bob.js'), 'w').write(
        "/* FRANK'S COMPUTER - Bob the panda (Datarails' mascot), 8-bit, for the Solitaire win. Generated by tools/make_bob.py. */\n"
        f"(() => {{ FR.data.images = FR.data.images || {{}}; FR.data.images.bob = 'data:image/png;base64,{base64.b64encode(png).decode()}'; }})();\n")
    print(f'bob: {w}x{h} pixels, {len(png) // 1024} KB -> src/bob.js')
